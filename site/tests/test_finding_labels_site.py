"""F29-T5 (R9; AC11): every statement is drawn by its label, the id stays in the title, and the
statement panel is headed by the label with the id beneath and a link to the gloss's controls.

The fixture is the routes page's (``two_routes``): three holes named in their partials (``hden``,
``hrem``, ``hthree``: ``label_source: hole``), a root whose label is its id, and here one hole
given a ``gloss/v3`` statement gloss carrying a label and a claim (``label_source: gloss``).
The products are generated by the gate, so the page reads exactly the contract's shape.
"""

from __future__ import annotations

import re
from pathlib import Path

import fixture
import gloss_fixture
import pytest
from harness import TARGET
from test_decompositions import HOLE_IDS
from test_products import ROOT_NODE
from test_routes_view import REPO, g_of, two_routes

from opn_gate import products
from opn_site import dag, model, render

LABEL = "Density of the sum"
CLAIM = r"\sum_{n \in A} \frac{1}{n} < 2"
GLOSSED, NAMED = HOLE_IDS


def labelled_pages(root: Path) -> dict[str, str]:
    """The products generated by the gate (the holes' own names, the root's id), then one hole
    given a gloss label on its row (the claim is the gate's, read from the gloss's opening) —
    the shape a ``gloss/v3`` statement gloss gives it (F29-R3)."""
    products.generate(root, rendered_from=fixture.COMMIT, commit_time=fixture.NOW).write(root)
    fixture.publish_labels(root, {GLOSSED: (LABEL, "gloss")})
    return render.render_site(model.load_site(root, fixture.COMMIT), repo_url=REPO)


def glossed_tree(tmp_path: Path) -> Path:
    root = two_routes(tmp_path)
    gloss_fixture.gloss(
        root,
        f"$${CLAIM}$$\n\nThe reciprocals of the set sum to less than two.",
        kind="statement",
        node=GLOSSED,
        author="ann",
    )
    return root


@pytest.fixture(scope="module")
def page(tmp_path_factory: pytest.TempPathFactory) -> str:
    root = glossed_tree(tmp_path_factory.mktemp("labels"))
    return labelled_pages(root)[f"problems/{TARGET}/index.html"]


def drawing(page: str, cls: str) -> str:
    start = page.index(f'<svg class="{cls}"')
    return page[start : page.index("</svg>", start)]


def pill_text(svg: str, node_id: str) -> str:
    m = re.search(r"<text[^>]*>([^<]*)</text>", g_of(svg, node_id))
    assert m is not None, node_id
    return m.group(1)


def title_of(svg: str, node_id: str) -> str:
    m = re.search(r"<title>([^<]*)</title>", g_of(svg, node_id))
    assert m is not None, node_id
    return m.group(1)


def panel(page: str, node_id: str) -> str:
    (hit,) = re.findall(
        rf'<div class="card panel" data-node="{re.escape(node_id)}".*?\n</div>', page, flags=re.S
    )
    return str(hit)


@pytest.mark.parametrize("cls", ["dag"])  # F30: one drawing (the routes drawing is gone)
def test_a_statement_is_drawn_by_its_label_and_the_id_stays_in_the_title(
    page: str, cls: str
) -> None:
    """AC11: the gloss's label on the pill; the hole's own name where that is all the record
    has; the short id where the label is the id. The title keeps the whole id either way."""
    svg = drawing(page, cls)
    assert pill_text(svg, GLOSSED) == LABEL
    assert GLOSSED in title_of(svg, GLOSSED) and LABEL in title_of(svg, GLOSSED)
    assert pill_text(svg, NAMED) == "hrem"
    assert NAMED in title_of(svg, NAMED)
    # The root's label is its id (the fixture target has no title): drawn as before, the
    # problem's own name dropped, and the title is the id alone.
    assert pill_text(svg, ROOT_NODE) == dag.label_of(ROOT_NODE, (TARGET, ROOT_NODE))
    assert title_of(svg, ROOT_NODE).startswith(f"{ROOT_NODE}:")


def test_the_panel_is_headed_by_the_label_with_the_id_beneath_and_a_rename_link(
    page: str,
) -> None:
    """R9: the heading is the label, the id sits beneath it in the panel-id style, the claim
    leads the body, and one link goes to the gloss's controls."""
    p = panel(page, GLOSSED)
    title = re.search(r'<span class="panel-title[^"]*">(.*?)</span>', p, re.S)
    assert title is not None and title.group(1) == LABEL
    assert p.index('class="panel-title') < p.index('class="panel-id"')
    assert f'<span class="panel-id">{GLOSSED}</span>' in p
    assert p.index('class="panel-id"') < p.index('data-section="claim"')
    assert "claim-math" in p and "frac{1}{n}" in p
    href = f"/nodes/{TARGET}/{GLOSSED}/#statement-words"
    assert re.search(rf'<a class="panel-rename" href="{re.escape(href)}">Rename or correct', p)


def test_an_id_labelled_statement_is_headed_by_its_id_once(page: str) -> None:
    p = panel(page, ROOT_NODE)
    title = re.search(r'<span class="panel-title[^"]*">(.*?)</span>', p, re.S)
    assert title is not None and title.group(1) == ROOT_NODE
    assert 'class="panel-id"' not in p
    assert "Rename or correct" in p  # the link is always there; the gloss page says who may


def test_a_long_label_gets_a_pill_measured_from_it() -> None:
    """A pill's width is computed from the label it shows (``CHAR_W`` a character), so a label
    at the 60-character limit never overflows its box."""
    long = "A label of exactly sixty characters, the most a gloss allows"
    assert len(long) == 60
    nodes = [{"node_id": "t--h1", "status": "ready", "deps": []}]
    labels = {"t--h1": long}
    out = dag.svg(nodes, href={"t--h1": "/x/"}, prefix="t", labels=labels)
    assert pill_text(out, "t--h1") == long
    (w,) = re.findall(r'<rect width="(\d+)"', out)
    assert int(w) == dag.node_width("t--h1", "t", labels=labels)
    assert int(w) >= 28 + round(dag.CHAR_W * len(long))
    assert dag.node_width("t--h1", "t") < int(w)


def test_the_label_channel_leaves_an_unlabelled_drawing_unchanged() -> None:
    nodes = [{"node_id": "t--h1", "status": "ready", "deps": []}]
    href = {"t--h1": "/x/"}
    assert dag.svg(nodes, href=href, prefix="t") == dag.svg(nodes, href=href, prefix="t", labels={})


def test_node_page_is_headed_by_the_label_too(tmp_path: Path) -> None:
    pages = labelled_pages(glossed_tree(tmp_path))
    node_page = pages[f"nodes/{TARGET}/{GLOSSED}/index.html"]
    assert f"<h1>{LABEL}</h1>" in node_page
    assert f'<p class="panel-id">{GLOSSED}</p>' in node_page
    plain = pages[f"nodes/{TARGET}/{ROOT_NODE}/index.html"]
    assert f'<h1 class="mono">{ROOT_NODE}</h1>' in plain
