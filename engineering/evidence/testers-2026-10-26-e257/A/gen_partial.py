"""Generate the finite-range partial on spec-a70fcca4--h4--h1--h2 (W(3m+2) for 1 <= m <= N,
hole: N < m), from the exact greedy walk of 1/2.

usage: python3 gen_partial.py N OUT.lean [WITNESS.lean]
Values r_n are computed to V = (next skipped step after N) and proved as one conjunction;
the finite range is closed by interval_cases in blocks of 25.
"""
import sys
from fractions import Fraction as F

N = int(sys.argv[1])
out = sys.argv[2]
wout = sys.argv[3] if len(sys.argv) > 3 else None

def e(n):
    return F(0) if n == 0 else F(1, 2**n - 1)

# walk
vals = [F(1, 2)]
skipped = set()
for m in range(0, 4 * N + 10):
    r = vals[-1]
    if e(m) <= r:
        vals.append(r - e(m))
    else:
        skipped.add(m)
        vals.append(r)

def next_skip(m):
    n = m + 1
    while n not in skipped:
        n += 1
    return n

V = next_skip(N)          # last value needed: the first skipped step after N
assert V <= 3 * N + 2
print("N =", N, " values to V =", V, " max denominator bits =", max(vals[n].denominator.bit_length() for n in range(V + 1)), file=sys.stderr)
for m in range(1, N + 1):
    if m in skipped:
        assert next_skip(m) <= 3 * m + 2, m

def lit(x):
    return f"{x.numerator} / {x.denominator}" if x.denominator != 1 else f"{x.numerator}"

REC = "(hrs : ∀ m : ℕ, r (m + 1) = if (1 : ℝ) / ((2 : ℝ) ^ m - 1) ≤ r m then r m - 1 / ((2 : ℝ) ^ m - 1) else r m)"
E = lambda n: f"(1 : ℝ) / ((2 : ℝ) ^ {n} - 1)"

L = []
L.append("import Mathlib")
L.append("import Nodes.«spec-a70fcca4--h4--h1--h2».Context")
L.append("")
L.append("/-! Hole `hrun` of a merged partial proof, as a node (D-12 #5, D-29).")
L.append("Statement generated by the gate from the assembly; immutable (D-3). -/")
L.append("")
# values lemma
conj = " ∧\n    ".join(f"r {n} = {lit(vals[n])}" for n in range(1, V + 1))
L.append(f"private theorem walk_values (r : ℕ → ℝ) (h0 : r 0 = 1 / 2)\n    {REC} :\n    {conj} := by")
for n in range(1, V + 1):
    prev = "h0" if n == 1 else f"v{n-1}"
    L.append(f"  have v{n} : r {n} = {lit(vals[n])} := by rw [hrs {n-1}, {prev}]; norm_num")
L.append("  exact ⟨" + ", ".join(f"v{n}" for n in range(1, V + 1)) + "⟩")
L.append("")

# finite range in blocks
BLOCK = 25
blocks = [(a, min(a + BLOCK - 1, N)) for a in range(1, N + 1, BLOCK)]
names = []
for (a, b) in blocks:
    name = f"range_{a}_{b}"
    names.append((name, a, b))
    L.append(f"private theorem {name} (r : ℕ → ℝ) (h0 : r 0 = 1 / 2)\n    {REC} :\n    ∀ m : ℕ, {a} ≤ m → m ≤ {b} → r m < {E('m')} →\n      ∃ n : ℕ, m < n ∧ n ≤ 3 * m + 2 ∧ r n < {E('n')} := by")
    L.append("  intro m hm1 hm2 hlt")
    L.append("  obtain ⟨" + ", ".join(f"v{n}" for n in range(1, V + 1)) + "⟩ := walk_values r h0 hrs")
    L.append("  interval_cases m")
    for m in range(a, b + 1):
        if m in skipped:
            n = next_skip(m)
            L.append(f"  · exact ⟨{n}, by norm_num, by norm_num, by rw [v{n}]; norm_num⟩")
        else:
            L.append(f"  · rw [v{m}] at hlt; norm_num at hlt")
    L.append("")

L.append("theorem spec_a70fcca4__h4__h1__h2 : ∀ (r : ℕ → ℝ),")
L.append("  r (0 : ℕ) = (1 / 2 : ℝ) →")
L.append("    (∀ (m : ℕ),")
L.append("        r (m + (1 : ℕ)) =")
L.append("          if (1 : ℝ) / ((2 : ℝ) ^ m - (1 : ℝ)) ≤ r m then r m - (1 : ℝ) / ((2 : ℝ) ^ m - (1 : ℝ)) else r m) →")
L.append("      ∀ (m : ℕ),")
L.append("        (1 : ℕ) ≤ m →")
L.append("          r m < (1 : ℝ) / ((2 : ℝ) ^ m - (1 : ℝ)) →")
L.append("            ∃ (n : ℕ), m < n ∧ n ≤ (3 : ℕ) * m + (2 : ℕ) ∧ r n < (1 : ℝ) / ((2 : ℝ) ^ n - (1 : ℝ)) := by")
L.append(f"  -- approach: the window statement is decided exactly for every skipped m ≤ {N} by computing the greedy walk of 1/2 to step {V} in the kernel (one `norm_num` per step); what remains is the same statement for m > {N}")
L.append("  -- licence: CC-BY-4.0")
L.append("  intro r h0 hrs")
L.append(f"  -- label: after a skipped m > {N}, another skip within (m, 3m+2]")
L.append(f"  -- claim: $m > {N} \\wedge r_m < \\frac{{1}}{{2^m-1}} \\Rightarrow \\exists n,\\ m < n \\le 3m+2 \\wedge r_n < \\frac{{1}}{{2^n-1}}$")
L.append(f"  -- The node's own statement restricted to m > {N}: the tail of the ladder W(3m+2), where no mechanism is known.")
L.append(f"  -- The range 1 ≤ m ≤ {N} is closed below by exact computation of the walk (steps 1 to {V}).")
L.append(f"  have htail : ∀ m : ℕ, {N} < m → r m < {E('m')} →")
L.append(f"      ∃ n : ℕ, m < n ∧ n ≤ 3 * m + 2 ∧ r n < {E('n')} := by")
L.append("    sorry")
L.append("  intro m hm hlt")
L.append(f"  by_cases hN : m ≤ {N}")
cond = " <;> ".join([])
# simple chain of by_cases on the block bounds
tac = []
for i, (nm, a, b) in enumerate(names):
    if i < len(names) - 1:
        tac.append(f"by_cases h{b} : m ≤ {b}")
        tac.append(f"· exact {nm} r h0 hrs m (by omega) h{b} hlt")
    else:
        tac.append(f"exact {nm} r h0 hrs m (by omega) hN hlt")
# nest properly
body = []
indent = "  · "
lines = []
depth = 0
for i, (nm, a, b) in enumerate(names):
    pad = "  " + "  " * depth
    if i < len(names) - 1:
        lines.append(f"{pad}by_cases h{b} : m ≤ {b}")
        lines.append(f"{pad}· exact {nm} r h0 hrs m (by omega) h{b} hlt")
        depth += 0
    else:
        lines.append(f"{pad}exact {nm} r h0 hrs m (by omega) hN hlt")
# Lean: after `· exact ...` for the positive case, the negative case continues at same indent
L.append("  · " + lines[0].strip())
for ln in lines[1:]:
    L.append("    " + ln.strip())
L.append("  · exact htail m (by omega) hlt")
L.append("")
open(out, "w").write("\n".join(L))
print("wrote", out, len(L), "lines", file=sys.stderr)

if wout:
    # witness for the hole: r the Nat.rec walk, m = V (skipped, V > N)
    W = []
    W.append("-- hole: htail")
    W.append("import Mathlib")
    W.append("")
    W.append("theorem witness : ∃ (r : ℕ → ℝ) (m : ℕ), r 0 = 1 / 2 ∧")
    W.append("    (∀ m, r (m + 1) = if (1 : ℝ) / (2 ^ m - 1) ≤ r m then r m - 1 / (2 ^ m - 1) else r m) ∧")
    W.append(f"    {N} < m ∧ r m < 1 / (2 ^ m - 1) := by")
    W.append("  obtain ⟨w, h0, hrs⟩ : ∃ w : ℕ → ℝ, w 0 = 1 / 2 ∧")
    W.append("      ∀ k : ℕ, w (k + 1) = if (1 : ℝ) / (2 ^ k - 1) ≤ w k then w k - 1 / (2 ^ k - 1) else w k :=")
    W.append("    ⟨fun m => Nat.rec (1 / 2 : ℝ)")
    W.append("      (fun k rk => if (1 : ℝ) / (2 ^ k - 1) ≤ rk then rk - 1 / (2 ^ k - 1) else rk) m, rfl, fun _ => rfl⟩")
    for n in range(1, V + 1):
        prev = "h0" if n == 1 else f"v{n-1}"
        W.append(f"  have v{n} : w {n} = {lit(vals[n])} := by rw [hrs {n-1}, {prev}]; norm_num")
    W.append(f"  exact ⟨w, {V}, h0, hrs, by norm_num, by rw [v{V}]; norm_num⟩")
    open(wout, "w").write("\n".join(W) + "\n")
    print("wrote", wout, file=sys.stderr)
